// Explicit developer refresh only. Runtime pricing never fetches currency data.
// Download the authoritative SIX List One XML separately, then review this diff.
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
const input = process.argv[2];
if (!input) throw Error('Pass the reviewed SIX List One XML path.');
const xml = await fs.readFile(input, 'utf8');
if (xml.includes('<!DOCTYPE') || xml.includes('<!ENTITY'))
  throw Error('Unsupported XML document.');
const values = new Map();
for (const match of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
  const code = match[1].match(/<Ccy>([A-Z]{3})<\/Ccy>/)?.[1],
    minor = match[1].match(/<CcyMnrUnts>([0-4])<\/CcyMnrUnts>/)?.[1];
  if (code && minor !== undefined) {
    if (values.has(code) && values.get(code) !== Number(minor))
      throw Error('Conflicting ISO minor units.');
    values.set(code, Number(minor));
  }
}
if (
  values.get('PKR') !== 2 ||
  values.get('JPY') !== 0 ||
  values.get('KWD') !== 3 ||
  values.size < 140
)
  throw Error('Currency dataset validation failed.');
const published = xml.match(/<ISO_4217\s+Pblshd="([0-9-]+)"/)?.[1];
if (!published) throw Error('Missing source publication date.');
const source =
  'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml';
await fs.writeFile(
  'src/operations/iso-currencies.ts',
  `// ISO 4217 numeric minor units from SIX List One; generated by the reviewed script.\n// Codes with no applicable minor unit are intentionally not selling currencies.\nexport const ISO_CURRENCY_SOURCE = ${JSON.stringify({ url: source, published, sha256: createHash('sha256').update(xml).digest('hex') })};\nexport const ISO_MINOR_UNITS: Readonly<Record<string,number>> = Object.freeze(${JSON.stringify(Object.fromEntries([...values].sort()), null, 2)});\n`,
);
console.log(
  `PASS ${values.size} ISO currencies; source published ${published}; PKR=2, JPY=0, KWD=3.`,
);
